"""Prepare credential-free Arduino inputs and identify their exact source bytes."""
from pathlib import Path
import hashlib
import json
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'firmware/IPhoneHIDBridge'
PROVENANCE_HEADER = 'BuildProvenance.h'
CLASSIC_GUARD = '!defined(CONFIG_IDF_TARGET_ESP32S3) && !defined(CONFIG_IDF_TARGET_ESP32C3)'


def source_hashes(folder):
    return {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(folder.iterdir()) if p.is_file() and p.name != PROVENANCE_HEADER}


def source_id(hashes):
    # File names and hashes are encoded unambiguously and identically on every host.
    return hashlib.sha256(json.dumps(hashes, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def prepare(destination, classic=False):
    if (SOURCE / 'config.h').exists():
        raise SystemExit('Refusing public build: private config.h exists')
    destination = destination.resolve()
    if (ROOT / 'firmware/build').resolve() not in destination.parents:
        raise SystemExit('Build inputs must remain inside firmware/build')
    destination.mkdir(parents=True, exist_ok=True)
    for previous in destination.iterdir():
        if previous.is_file():
            previous.unlink()
    for source in SOURCE.iterdir():
        if source.is_file() and source.name != PROVENANCE_HEADER:
            shutil.copyfile(source, destination / source.name)
    if classic:
        bridge = destination / 'Bridge.cpp'
        text = bridge.read_text()
        assert text.count(CLASSIC_GUARD) == 1
        bridge.write_text(text.replace(CLASSIC_GUARD, '!defined(CONFIG_IDF_TARGET_ESP32) && ' + CLASSIC_GUARD))
    fingerprint = source_id(source_hashes(destination))
    (destination / PROVENANCE_HEADER).write_text(
        '// Generated by scripts/firmware_provenance.py; no private configuration.\n'
        '#pragma once\n#define SIGHTLATCH_BUILD_SOURCE_SHA256 "' + fingerprint + '"\n')
    print(fingerprint)


if __name__ == '__main__':
    prepare(Path(sys.argv[1]), classic='--classic' in sys.argv[2:])
